missing = []
for sid, it in papers:
    pid = (it.get("paper_id") or "").strip()
    if not pid:
        key = SPECIAL.get((sid, it.get("title", "")))
        if not key:
            missing.append((sid, it.get("title")))
            continue
        pid = key
    if pid not in all_sum:
        missing.append((sid, pid, it.get("title")))
        continue
    final[pid] = all_sum[pid]

